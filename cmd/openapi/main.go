// Command openapi renders api/openapi/openapi.yaml from contracts/httpapi.
// The route manifest and the DTO struct tags are the only sources; the YAML in
// the repository is a generated artifact. Run with -check in CI or `make
// openapi-check` to fail when a contract change was not regenerated.
package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"reflect"
	"regexp"
	"sort"
	"strconv"
	"strings"
	"time"

	contract "github.com/hzc19970630/rag-platform/contracts/httpapi"
	"gopkg.in/yaml.v3"
)

const defaultOutput = "api/openapi/openapi.yaml"

func main() {
	output := flag.String("out", defaultOutput, "path of the generated OpenAPI document")
	check := flag.Bool("check", false, "verify the checked-in document matches the contracts")
	flag.Parse()

	generated, err := Generate()
	if err != nil {
		fmt.Fprintf(os.Stderr, "generate openapi: %v\n", err)
		os.Exit(1)
	}
	if *check {
		existing, err := os.ReadFile(*output)
		if err != nil {
			fmt.Fprintf(os.Stderr, "read %s: %v\n", *output, err)
			os.Exit(1)
		}
		if stale(existing, generated) {
			fmt.Fprintf(os.Stderr, "%s is stale; run `go run ./cmd/openapi` and commit the result\n", *output)
			os.Exit(1)
		}
		return
	}
	if err := os.MkdirAll(filepath.Dir(*output), 0o755); err != nil {
		fmt.Fprintf(os.Stderr, "create output directory: %v\n", err)
		os.Exit(1)
	}
	if err := os.WriteFile(*output, generated, 0o644); err != nil {
		fmt.Fprintf(os.Stderr, "write %s: %v\n", *output, err)
		os.Exit(1)
	}
}

// stale compares the checked-in document with freshly generated bytes. A
// Windows checkout may hold CRLF line endings, which are not a contract change.
func stale(existing, generated []byte) bool {
	return !bytes.Equal(normalizeNewlines(existing), normalizeNewlines(generated))
}

func normalizeNewlines(data []byte) []byte {
	return bytes.ReplaceAll(data, []byte("\r\n"), []byte("\n"))
}

// Generate builds the OpenAPI document bytes. It is exported so tests can
// assert determinism and reference resolution without touching the working
// tree.
func Generate() ([]byte, error) {
	generator := &schemaGenerator{schemas: map[string]any{}, building: map[reflect.Type]bool{}}
	paths, tags := generator.paths()
	// The shared error envelope is referenced by response components, not by a
	// route body, so it must be registered explicitly.
	generator.component(reflect.TypeOf(contract.Error{}))

	document := map[string]any{
		"openapi": "3.0.3",
		"info": map[string]any{
			"title":   "RAG Platform API",
			"version": "0.10.0",
			"description": "Resource-oriented contract for the RAG platform. Route ownership follows the\n" +
				"domain resource, not the delivery milestone. This file is generated from\n" +
				"contracts/httpapi; every Gin business route must have a matching entry there\n" +
				"(see openapi_test.go).",
		},
		"servers":  []any{map[string]any{"url": "/api/v1"}},
		"security": []any{map[string]any{"bearerAuth": []string{}}, map[string]any{"sessionCookie": []string{}}},
		"tags":     tags,
		"components": map[string]any{
			"securitySchemes": map[string]any{
				"bearerAuth":    map[string]any{"type": "http", "scheme": "bearer"},
				"sessionCookie": map[string]any{"type": "apiKey", "in": "cookie", "name": "rag_session"},
			},
			"responses": commonResponses(),
			"schemas":   generator.schemas,
		},
		"paths": paths,
	}

	var buffer bytes.Buffer
	encoder := yaml.NewEncoder(&buffer)
	encoder.SetIndent(2)
	if err := encoder.Encode(document); err != nil {
		return nil, err
	}
	if err := encoder.Close(); err != nil {
		return nil, err
	}
	return buffer.Bytes(), nil
}

func commonResponses() map[string]any {
	return map[string]any{
		"BadRequest":    errorResponse("Invalid request"),
		"Unauthorized":  errorResponse("Authentication required or invalid"),
		"Forbidden":     errorResponse("The caller may not access this resource"),
		"InternalError": errorResponse("Unexpected server error"),
	}
}

func errorResponse(description string) map[string]any {
	return map[string]any{
		"description": description,
		"content": map[string]any{
			"application/json": map[string]any{
				"schema": map[string]any{"$ref": "#/components/schemas/Error"},
			},
		},
	}
}

func (g *schemaGenerator) paths() (map[string]any, []any) {
	paths := map[string]any{}
	var tags []any
	seenTags := map[string]bool{}
	for _, route := range contract.Routes {
		if !seenTags[route.Tag] {
			seenTags[route.Tag] = true
			tags = append(tags, map[string]any{"name": route.Tag})
		}
		methods, ok := paths[route.Path].(map[string]any)
		if !ok {
			methods = map[string]any{}
			paths[route.Path] = methods
		}
		methods[strings.ToLower(route.Method)] = g.operation(route)
	}
	return paths, tags
}

func (g *schemaGenerator) operation(route contract.Route) map[string]any {
	operation := map[string]any{
		"tags":        []string{route.Tag},
		"summary":     route.Method + " " + route.Path,
		"operationId": route.OperationID,
		"responses":   g.responses(route),
	}
	if route.Public {
		operation["security"] = []any{}
	}
	if parameters := pathParameters(route.Path); len(parameters) > 0 {
		operation["parameters"] = parameters
	}
	if route.Request != nil {
		operation["requestBody"] = g.requestBody(*route.Request)
	}
	return operation
}

func (g *schemaGenerator) requestBody(body contract.RequestBody) map[string]any {
	contentType := body.ContentType
	if contentType == "" {
		contentType = "application/json"
	}
	return map[string]any{
		"required": body.Required,
		"content": map[string]any{
			contentType: map[string]any{"schema": g.schemaForValue(body.Schema)},
		},
	}
}

func (g *schemaGenerator) responses(route contract.Route) map[string]any {
	responses := map[string]any{
		strconv.Itoa(route.Success.Status): g.successResponse(route.Success),
	}
	for _, status := range route.Errors {
		responses[strconv.Itoa(status)] = map[string]any{"$ref": "#/components/responses/" + errorComponent(status)}
	}
	return responses
}

func (g *schemaGenerator) successResponse(response contract.Response) map[string]any {
	description := response.Description
	if description == "" {
		switch response.Status {
		case 200:
			description = "Success"
		case 201:
			description = "Created"
		case 202:
			description = "Accepted"
		case 204:
			description = "No content"
		default:
			description = "Response"
		}
	}
	result := map[string]any{"description": description}
	if response.Schema == nil && !response.Binary {
		return result
	}
	contentType := response.ContentType
	if contentType == "" {
		contentType = "application/json"
	}
	schema := map[string]any{"type": "string", "format": "binary"}
	if !response.Binary {
		schema = g.schemaForValue(response.Schema)
	}
	result["content"] = map[string]any{
		contentType: map[string]any{"schema": schema},
	}
	return result
}

func errorComponent(status int) string {
	switch status {
	case 400:
		return "BadRequest"
	case 401:
		return "Unauthorized"
	case 403:
		return "Forbidden"
	case 500:
		return "InternalError"
	default:
		return "InternalError"
	}
}

var pathParameterPattern = regexp.MustCompile(`\{([^}]+)\}`)

func pathParameters(path string) []any {
	matches := pathParameterPattern.FindAllStringSubmatch(path, -1)
	if len(matches) == 0 {
		return nil
	}
	parameters := make([]any, 0, len(matches))
	for _, match := range matches {
		parameters = append(parameters, map[string]any{
			"name":     match[1],
			"in":       "path",
			"required": true,
			"schema":   map[string]any{"type": "string"},
		})
	}
	return parameters
}

type schemaGenerator struct {
	schemas  map[string]any
	building map[reflect.Type]bool
}

func (g *schemaGenerator) schemaForValue(value any) map[string]any {
	if value == nil {
		return map[string]any{}
	}
	return g.schemaFor(reflect.TypeOf(value))
}

func (g *schemaGenerator) schemaFor(valueType reflect.Type) map[string]any {
	for valueType.Kind() == reflect.Pointer {
		valueType = valueType.Elem()
	}
	if valueType.Name() != "" && valueType.PkgPath() == reflect.TypeOf(contract.Error{}).PkgPath() {
		return map[string]any{"$ref": "#/components/schemas/" + g.component(valueType)}
	}
	return g.underlyingSchema(valueType)
}

// underlyingSchema describes a type without turning its own name into a
// component reference. component() uses it for the definition body.
func (g *schemaGenerator) underlyingSchema(valueType reflect.Type) map[string]any {
	for valueType.Kind() == reflect.Pointer {
		valueType = valueType.Elem()
	}
	if valueType == reflect.TypeOf(time.Time{}) {
		return map[string]any{"type": "string", "format": "date-time"}
	}
	if valueType == reflect.TypeOf(json.RawMessage{}) {
		return map[string]any{}
	}
	switch valueType.Kind() {
	case reflect.Struct:
		return g.structSchema(valueType)
	case reflect.Slice, reflect.Array:
		return map[string]any{"type": "array", "items": g.schemaFor(valueType.Elem())}
	case reflect.Map:
		additional := any(true)
		if item := g.schemaFor(valueType.Elem()); len(item) > 0 {
			additional = item
		}
		return map[string]any{"type": "object", "additionalProperties": additional}
	case reflect.Interface:
		return map[string]any{}
	case reflect.String:
		return map[string]any{"type": "string"}
	case reflect.Bool:
		return map[string]any{"type": "boolean"}
	case reflect.Int64, reflect.Uint64:
		return map[string]any{"type": "integer", "format": "int64"}
	case reflect.Int, reflect.Int8, reflect.Int16, reflect.Int32,
		reflect.Uint, reflect.Uint8, reflect.Uint16, reflect.Uint32:
		return map[string]any{"type": "integer"}
	case reflect.Float32, reflect.Float64:
		return map[string]any{"type": "number"}
	default:
		return map[string]any{}
	}
}

func (g *schemaGenerator) component(valueType reflect.Type) string {
	name := valueType.Name()
	if _, ok := g.schemas[name]; ok {
		return name
	}
	if g.building[valueType] {
		return name
	}
	g.building[valueType] = true
	defer delete(g.building, valueType)

	g.schemas[name] = g.underlyingSchema(valueType)
	return name
}

func (g *schemaGenerator) structSchema(valueType reflect.Type) map[string]any {
	properties := map[string]any{}
	required := []string{}
	seenRequired := map[string]bool{}
	for index := 0; index < valueType.NumField(); index++ {
		field := valueType.Field(index)
		if field.PkgPath != "" {
			continue
		}
		name, _ := splitTag(field.Tag.Get("json"))
		if name == "-" {
			continue
		}
		if name == "" {
			if field.Anonymous {
				g.structProperties(field.Type, properties, &required, seenRequired)
				continue
			}
			name = field.Name
		}
		property := g.schemaFor(field.Type)
		applyOATags(property, field.Tag.Get("oa"))
		if tagRequires(field.Tag.Get("oa"), "required") || bindingRequires(field.Tag.Get("binding")) {
			if !seenRequired[name] {
				seenRequired[name] = true
				required = append(required, name)
			}
		}
		properties[name] = property
	}
	schema := map[string]any{"type": "object"}
	if len(properties) > 0 {
		schema["properties"] = properties
	}
	if len(required) > 0 {
		sort.Strings(required)
		schema["required"] = required
	}
	return schema
}

// structProperties flattens an anonymous embedded struct. None of the wire
// DTOs use embedding today, but reflection must not silently drop such fields.
func (g *schemaGenerator) structProperties(valueType reflect.Type, properties map[string]any, required *[]string, seenRequired map[string]bool) {
	for valueType.Kind() == reflect.Pointer {
		valueType = valueType.Elem()
	}
	if valueType.Kind() != reflect.Struct {
		return
	}
	for index := 0; index < valueType.NumField(); index++ {
		field := valueType.Field(index)
		if field.PkgPath != "" {
			continue
		}
		name, _ := splitTag(field.Tag.Get("json"))
		if name == "-" {
			continue
		}
		if name == "" {
			g.structProperties(field.Type, properties, required, seenRequired)
			continue
		}
		property := g.schemaFor(field.Type)
		applyOATags(property, field.Tag.Get("oa"))
		if tagRequires(field.Tag.Get("oa"), "required") || bindingRequires(field.Tag.Get("binding")) {
			if !seenRequired[name] {
				seenRequired[name] = true
				*required = append(*required, name)
			}
		}
		properties[name] = property
	}
}

func splitTag(tag string) (string, []string) {
	if tag == "" {
		return "", nil
	}
	parts := strings.Split(tag, ",")
	return parts[0], parts[1:]
}

func bindingRequires(tag string) bool {
	for _, option := range strings.Split(tag, ",") {
		if strings.TrimSpace(option) == "required" {
			return true
		}
	}
	return false
}

func tagRequires(tag, option string) bool {
	for _, item := range strings.Split(tag, ",") {
		if strings.TrimSpace(item) == option {
			return true
		}
	}
	return false
}

func applyOATags(schema map[string]any, tag string) {
	for _, item := range strings.Split(tag, ",") {
		item = strings.TrimSpace(item)
		if item == "" || item == "required" {
			continue
		}
		key, value, hasValue := strings.Cut(item, "=")
		switch key {
		case "maxLength":
			if parsed, err := strconv.Atoi(value); err == nil {
				schema["maxLength"] = parsed
			}
		case "minLength":
			if parsed, err := strconv.Atoi(value); err == nil {
				schema["minLength"] = parsed
			}
		case "min":
			if parsed, err := strconv.Atoi(value); err == nil {
				schema["minimum"] = parsed
			}
		case "max":
			if parsed, err := strconv.Atoi(value); err == nil {
				schema["maximum"] = parsed
			}
		case "enum":
			if hasValue {
				schema["enum"] = strings.Split(value, "|")
			}
		case "binary":
			schema["type"] = "string"
			schema["format"] = "binary"
		case "format":
			if hasValue {
				schema["format"] = value
			}
		}
	}
}
